"""工作台域（P4-5 / F4-10~F4-12）。

四块东西，各管一件事：

    chat.py    会话与轮次：消息落库、起一轮对话、回退
    skills.py  七个内置技能：Agent 能对课程做的**全部**修改都在这里
    agent.py   把一轮对话编排起来：规划 → 流式回复 → 执行技能 → 收尾
    stream.py  会话级 SSE 扇出（这一轮的消息往哪推）

与生成域的分工：生成域从零写一门课，工作台域在**已经写好的课**上改 ——
所以这里复用 `generation` 的模型调用与提示词、复用 `courses.library` 的写页与
重写，而不另起一套。
"""

#: 工作台这条路上的每一次模型调用都记在 `chat` 名下（P5-C2 的账本口径）。
#:
#: 生成域的调用有 `job_id`，账本按 job 归集就够了；工作台**没有任务** ——
#: 它不是异步任务，是用户坐在那儿一问一答。所以归属只能由调用点显式给，
#: 而 `ref_id` 是课程 id：账本的第一个问题永远是「这门课的钱花在哪了」，
#: 工作台的改动也落在那门课上（`skills.py` 的七个技能全是改课）。
#:
#: 写成一个常量是因为这四个调用点必须给同一个值：分叉的症状是「看板上
#: 这门课的成本少了一块」，而那是看不出错的 —— 少记的账不会报错。
REF_TYPE_CHAT = "chat"

__all__ = ["REF_TYPE_CHAT"]
