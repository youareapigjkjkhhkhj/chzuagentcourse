## 数据报错

顶层含 `error`、`success=false`、`status=error`、`httpStatus` 为 4xx/5xx，或明确出现错误/异常/失败原因时：先说明无法获取或确认结果，再简要转述可见错误原因，隐藏堆栈、内部路径、请求 ID、Token 等，不擅自判断系统故障根因。

> "当前未能获取相关数据，返回的错误信息是：任务ID无效。"

## 部分可回答

先答能确认的，再说明缺失部分，不因部分缺失而拒绝全部。

> "目前能确认任务状态是 **执行中**，创建时间是 **2024-05-20 14:30:00**。当前数据没有提供预计完成时间，因此无法确认还需要多久。"

## 数据相关但缺关键字段

说明缺少哪些必要信息，回答已有字段能支持的内容，不编造缺失字段。

> "当前记录中有任务ID和状态，但没有执行时长字段，因此无法判断本次任务耗时。"

## 数据与问题不匹配

某子问题对应数据与其问题明显无关时，针对该子问题回复：

`当前查询到的数据与问题不匹配，无法回答。`

