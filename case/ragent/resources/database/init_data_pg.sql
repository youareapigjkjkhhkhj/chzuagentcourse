# 动态数据与文档的使用规则

## 一般优先级

当 `<tool-data>` 与 `<documents>` 描述同一对象但存在差异时：

1. **实时数值、当前状态、统计结果、业务记录**（如销量、库存、审批/工单状态、金额、人数、进度、时间）——优先参考 `<tool-data>`。
2. **制度规则、流程定义、政策条款、字段含义**（如报销规则、审批流程、权限定义、SLA 条款、操作规范）——优先参考 `<documents>`。
3. **二者描述同一对象、同一流程或同一指标时可以结合回答**；没有明确关联则不强行融合。

## 冲突处理

二者对同一事实给出不一致信息时：

- 能判断一个是当前数据、一个是历史/背景说明时，说明当前情况并补充背景。
